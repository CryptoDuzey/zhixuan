/**
 * 只返回平台阅读建议；调用方另拼 MARKETING_SCENARIO_GUIDANCE。
 * 未确定平台时返回空串，不擅自选择平台；非法值抛错，不拼接原始输入。
 */
export function buildMarketingPlatformGuidance(platform?: Platform | null): string {
  if (platform === undefined || platform === null) return '';
  if (typeof platform !== 'string' || !Object.hasOwn(PLATFORM_GUIDANCE, platform)) {
    throw new RangeError('不支持的内容平台');
  }
  return PLATFORM_GUIDANCE[platform];
}
